"""The automatic reply text (D-005). Edit the wording here and only here."""

from html import escape

from . import config

GREETING = "Hi,"
FOUND_LINE = "Please find attached the Proof of Delivery for {numbers}."
NOT_RECEIVED_LINE = (
    "We have not received the Proof of Delivery for {numbers} yet. "
    "We will send it to you as soon as we receive it."
)
# A number a person has checked and Power BI still does not know (D-045).
NOT_IN_SYSTEM_LINE = (
    "Regarding {numbers}, we were unable to find {it} in our system. "
    "Could you please check the {number} and let us know? We will be happy to look into it further."
)
AUTOMATED_NOTICE = "This email was automatically generated by the POD Email Agent."
SIGN_OFF = "Kind regards,\nPOD Teams"
# Used when POD_SIGNATURE_FILE is not set. The company's own signature (name,
# address, phone, website) lives in that file, outside the repository.
DEFAULT_SIGNATURE_HTML = """
<div style="font-family:Arial,sans-serif;font-size:11pt;line-height:1.5;margin-top:16px;">
  <p style="margin:0 0 18px;color:#1f4e79;font-weight:bold;">
    Kind Regards,<br>POD Teams
  </p>
</div>
"""


def _join(numbers: list[str]) -> str:
    values = [str(value).strip() for value in numbers if str(value).strip()]
    if len(values) <= 1:
        return "".join(values)
    return ", ".join(values[:-1]) + f" and {values[-1]}"


def build_reply(
    found: list[str], not_received: list[str], not_in_system: list[str] = (), *, include_notice: bool = True
) -> str:
    """Build one reply per email, optionally including the automated notice."""
    if not found and not not_received and not not_in_system:
        raise ValueError("A reply needs at least one found, not-received or not-in-system number")
    paragraphs = [GREETING]
    if found:
        paragraphs.append(FOUND_LINE.format(numbers=_join(found)))
    if not_received:
        paragraphs.append(NOT_RECEIVED_LINE.format(numbers=_join(not_received)))
    if not_in_system:
        several = len(not_in_system) > 1
        paragraphs.append(NOT_IN_SYSTEM_LINE.format(
            numbers=_join(list(not_in_system)), it="them" if several else "it", number="numbers" if several else "number"))
    if include_notice:
        paragraphs.append(AUTOMATED_NOTICE)
    paragraphs.append(SIGN_OFF)
    return "\n\n".join(paragraphs)


def build_reply_fragment(body: str) -> str:
    """Format the generated reply and company signature as an HTML fragment."""
    if not body.endswith(SIGN_OFF):
        raise ValueError("Reply body must end with the configured sign-off")
    message = body[: -len(SIGN_OFF)].rstrip()
    paragraphs = []
    for paragraph in message.split("\n\n"):
        style = (
            "margin:0 0 12px;font-size:9pt;font-style:italic;color:#666666;"
            if paragraph == AUTOMATED_NOTICE else "margin:0 0 12px;"
        )
        paragraphs.append(
            f'<p style="{style}">{escape(paragraph).replace(chr(10), "<br>")}</p>'
        )
    return f"{''.join(paragraphs)}{config.signature_html() or DEFAULT_SIGNATURE_HTML}"


def build_reply_html(body: str, quoted_html: str, outlook_head: str = "") -> str:
    """Format the generated reply with the company signature and quoted email."""
    return (
        f"<html><head>{outlook_head}</head>"
        '<body style="font-family:Arial,sans-serif;font-size:11pt;color:#222222;">'
        f"{build_reply_fragment(body)}{quoted_html}</body></html>"
    )
